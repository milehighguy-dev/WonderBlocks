import {writeFile} from 'node:fs/promises';
import {SURFACES,surfacePixels} from '../src/materials/surfaces.js';
import {FLORA_ASSETS} from '../src/flora/flora-palette.js';
import {sourceTextureKey,textureLabel} from '../src/swbf2/swbf2-texture-names.js';

// Offline, deterministic labels for identical library image data. No game
// pixels are copied into this index; it contains fingerprints and names only.
const names=new Map();
function add(image,label){
 if(!image?.data||!image.width||!image.height)return;
 for(const flip of [false,true]){const key=sourceTextureKey(image,{flip}),name=textureLabel(label);if(!names.has(key)||name<names.get(key))names.set(key,name);}
}
for(const s of [...SURFACES].sort((a,b)=>a.id.localeCompare(b.id)))add({width:128,height:128,data:surfacePixels(s.id)},s.name);
for(const asset of [...FLORA_ASSETS].sort((a,b)=>a.id.localeCompare(b.id)))if(asset.textureMap)add(asset.textureMap()?.image,asset.name);
const entries=Object.fromEntries([...names].sort(([a],[b])=>a.localeCompare(b)));
await writeFile(new URL('../src/swbf2/data/texture-name-catalog.js',import.meta.url),'// Generated by tools/build-texture-name-catalog.mjs; image fingerprints and labels only.\nexport const TEXTURE_NAME_CATALOG='+JSON.stringify(entries,null,2)+';\n');
console.log('Indexed '+names.size+' library texture orientations.');
