"""Read-only extraction of the stock Yavin twig card and its original alpha texture."""
import argparse, base64, hashlib, json, math, struct
from pathlib import Path
from PIL import Image

def chunks(data, at=0):
    while at+8<=len(data):
        tag=data[at:at+4].decode('ascii');size=struct.unpack_from('<I',data,at+4)[0]
        if at+8+size>len(data):raise ValueError('Truncated '+tag)
        yield tag,data[at+8:at+8+size];at+=8+size

def array(data,width,code='f'):
    n=struct.unpack_from('<I',data)[0];a=struct.unpack_from('<'+str(n*width)+code,data,4)
    return [list(a[i:i+width]) for i in range(0,len(a),width)]

def dot(a,b):return sum(x*y for x,y in zip(a,b))
def sub(a,b):return [x-y for x,y in zip(a,b)]
def unit(a):return [x/math.sqrt(dot(a,a)) for x in a]
def cross(a,b):return [a[1]*b[2]-a[2]*b[1],a[2]*b[0]-a[0]*b[2],a[0]*b[1]-a[1]*b[0]]

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--source',default='C:/SWBF2_ModTools/BF2_ModTools/assets/worlds/YAV/msh');args=parser.parse_args()
    root=Path(args.source);model=root/'yav_prop_leaftree3.msh';texture=root/'yav_prop_leaftree_branch.tga'
    msh=dict(chunks(dict(chunks(model.read_bytes()))['HEDR']))['MSH2'];materials=[];selected=None;study=[]
    for tag,data in chunks(msh):
        if tag=='MATL':
            for _,body in chunks(data,4):
                fields=dict(chunks(body));materials.append({'texture':fields.get('TX0D',b'').split(b'\0')[0].decode(),'flags':list(fields.get('ATRB',b''))})
        if tag!='MODL':continue
        fields=dict(chunks(data));name=fields['NAME'].split(b'\0')[0].decode()
        if struct.unpack('<I',fields['MTYP'])[0]!=4 or any(fields.get('FLGS',b'')) or any(s in name.lower() for s in ['lowrez','lowres','shadow','collision']):continue
        for tag,body in chunks(fields.get('GEOM',b'')):
            if tag!='SEGM':continue
            seg=dict(chunks(body));material=materials[struct.unpack('<I',seg['MATI'])[0]]
            if material['texture']!=texture.name:continue
            entry={'node':name,'positions':array(seg['POSL'],3),'uv':array(seg['UV0L'],2),'indices':array(seg['NDXT'],3,'H'),'materialFlags':material['flags']}
            study.append({'node':name,'triangles':len(entry['indices']),'vertices':len(entry['positions'])})
            if name=='branch26':selected=entry
    if not selected or len(selected['indices'])!=2:raise ValueError('Expected the stock branch26 two-triangle card')
    p=selected['positions'];uv=selected['uv'];origin=min(range(len(p)),key=lambda i:(uv[i][0]-1)**2+uv[i][1]**2);tip=min(range(len(p)),key=lambda i:(uv[i][0]-1)**2+(uv[i][1]-1)**2)
    y=unit(sub(p[tip],p[origin]));left=min(range(len(p)),key=lambda i:uv[i][0]**2+uv[i][1]**2);v=sub(p[origin],p[left]);x=unit([v[i]-dot(v,y)*y[i] for i in range(3)]);z=cross(x,y);length=math.dist(p[tip],p[origin]);scale=2/length
    positions=[round(dot(sub(point,p[origin]),axis)*scale,8) for point in p for axis in [x,y,z]]
    indices=[]
    for a,b,c in selected['indices']:
        points=[positions[i*3:i*3+3] for i in [a,b,c]]
        indices.extend([a,b,c] if cross(sub(points[1],points[0]),sub(points[2],points[0]))[2]>0 else [a,c,b])
    image=Image.open(texture).convert('RGBA');repo=Path(__file__).resolve().parents[1]
    image.save(repo/'assets/swbf-foliage/yavin-branch.png')
    source={'source':'YAV/msh/yav_prop_leaftree3.msh · branch26','modelSHA256':hashlib.sha256(model.read_bytes()).hexdigest(),'sourceVertices':p,'sourceAnchor':p[origin],'sourceUV':uv,'sourceIndices':selected['indices'],'materialFlags':selected['materialFlags'],'normalization':{'basis':[x,y,z],'scale':scale,'stemLengthMetres':2},'positions':positions,'uv':[v for point in uv for v in point],'indices':indices,'stockBranchPlanes':study,'texture':{'source':'YAV/msh/'+texture.name,'sha256':hashlib.sha256(texture.read_bytes()).hexdigest(),'width':image.width,'height':image.height,'rgba':base64.b64encode(image.transpose(Image.Transpose.FLIP_TOP_BOTTOM).tobytes()).decode()}}
    (repo/'src/flora/data/yavin-branch-source.js').write_text('// Generated by tools/extract-yavin-branches.py; original stock UVs and alpha pixels.\nexport const YAVIN_BRANCH_SOURCE='+json.dumps(source,separators=(',',':'))+';\n')
    print(json.dumps({'source':source['source'],'textureSize':image.size,'branchPlanes':study,'sourceTriangles':len(indices)//3}))

if __name__=='__main__':main()
