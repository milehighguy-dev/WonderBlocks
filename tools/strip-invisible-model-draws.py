"""Remove draws from fully transparent native carriers, retaining model/physics.

Run after ModelMunge, before LevelPack: SCRIPT WORLD_SOURCE COMPILED_DIRECTORY.
RedModel::Read (007f9fb0) explicitly accepts INFO segment count zero. Its render
path (007fab70) skips lighting collection for such models. Keep gmod, bounds,
poses, collision and model identity: EntityProp still needs the model resource.
This edits asset containers, never the game executable.
"""
from pathlib import Path
import argparse
import json
import struct


def fields(data):
    offset = 0
    while offset < len(data):
        if offset + 8 > len(data):
            raise ValueError('Truncated chunk header')
        tag, size = struct.unpack_from('<4sI', data, offset)
        end = offset + 8 + size
        next_offset = (end + 3) & ~3
        if next_offset > len(data):
            raise ValueError('Truncated chunk')
        yield tag, data[offset + 8:end]
        offset = next_offset


def chunk(tag, data):
    return tag + struct.pack('<I', len(data)) + data + bytes(-len(data) % 4)


def transparent_textures(source):
    result = set()
    for path in source.rglob('*.tga'):
        data = path.read_bytes()
        if len(data) < 18 or data[1:3] != b'\0\2' or data[16] != 32:
            continue
        width, height = struct.unpack_from('<HH', data, 12)
        start = 18 + data[0]
        if width and height and len(data) == start + width * height * 4 and not any(data[start:]):
            result.add(path.stem.lower())
    return result


def invisible_segment(data, transparent):
    items = list(fields(data))
    props = dict(items)
    # Exact native material generated by the cutout carrier flags (24).
    if props.get(b'RTYP') != b'Normal\0' or props.get(b'MTRL', b'')[:4] != b'\3\0\1\0':
        return False
    textures = [(struct.unpack_from('<I', v)[0], v[4:].rstrip(b'\0').decode())
                for t, v in items if t == b'TNAM']
    return (any(slot == 0 and name.lower() in transparent for slot, name in textures)
            and all(slot == 0 or not name for slot, name in textures))


def strip_model(data, transparent):
    roots = list(fields(data))
    if len(roots) != 1 or roots[0][0] != b'ucfb':
        raise ValueError('Expected UCFB model container')
    output, changed = [], []
    for tag, body in fields(roots[0][1]):
        if tag == b'modl':
            items = list(fields(body))
            props = dict(items)
            segments = [v for t, v in items if t == b'segm']
            info = props.get(b'INFO', b'')
            if segments and all(invisible_segment(v, transparent) for v in segments):
                if len(info) != 72 or struct.unpack_from('<I', info, 8)[0] != len(segments):
                    raise ValueError('Unexpected carrier segment layout')
                if any(t == b'shdw' for t, _ in items):
                    raise ValueError('Transparent carrier has a shadow')
                # INFO[2] is segment count. Preserve bounds, skinning metadata,
                # model identity, vertex count diagnostic and every other field.
                body = b''.join(chunk(t, v[:8] + bytes(4) + v[12:] if t == b'INFO' else v)
                                for t, v in items if t != b'segm')
                changed.append(props[b'NAME'].rstrip(b'\0').decode())
        output.append(chunk(tag, body))
    return (chunk(b'ucfb', b''.join(output)) if changed else data), changed


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('compiled', type=Path)
    args = parser.parse_args()
    transparent = transparent_textures(args.source)
    result = {}
    for path in sorted(args.compiled.glob('*.model')):
        raw = path.read_bytes()
        new, names = strip_model(raw, transparent)
        if names:
            path.write_bytes(new)
            result[path.name] = names
    (args.compiled / 'invisible-model-draws.json').write_text(json.dumps({
        'transparentTextureSources': sorted(transparent), 'models': result,
        'drawsRemoved': sum(map(len, result.values())),
        'collisionAndBoundsPreserved': True,
    }, indent=2))
    print('Removed lighting/draw submissions from', sum(map(len, result.values())), 'invisible models.')


if __name__ == '__main__':
    main()
